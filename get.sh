#!/bin/bash
# =============================================================================
# Network Doctor one-line installer for macOS
#
# Usage:  curl -fsSL https://raw.githubusercontent.com/jgonzalez007/netdiag/main/get.sh | bash
#
# What it installs:
#   • netdiag (CLI diagnostic tool)
#   • netdiag-web.py (web dashboard server)
#   • monitor.sh (background network & VPN watcher)
#   • Network Doctor.app (launchable app)
#
# The background monitor runs automatically once installed (no login item).
# Logs: ~/Library/Logs/jgonzalez007/network-doctor.log
# =============================================================================

set -euo pipefail

REPO="${NETDIAG_REPO:-https://raw.githubusercontent.com/jgonzalez007/netdiag/main}"
DIR="$HOME/.netdiag/app"
APP="$HOME/Applications/Network Doctor.app"
LABEL=com.jgonzalez007.network-doctor

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }

[ "$(uname -s)" = Darwin ] || { echo "Network Doctor runs on macOS only."; exit 1; }

# Check for Python (needed by web server)
if ! xcode-select -p >/dev/null 2>&1; then
    say "One-time setup: Network Doctor needs Apple's Command Line Tools."
    xcode-select --install >/dev/null 2>&1 || true
    exit 1
fi

say "Installing Network Doctor…"
mkdir -p "$DIR"

# Install netdiag CLI
curl -fsSL "$REPO/netdiag" -o "$DIR/netdiag"
chmod +x "$DIR/netdiag"

# Install web dashboard
curl -fsSL "$REPO/netdiag-web.py" -o "$DIR/netdiag-web.py"
chmod +x "$DIR/netdiag-web.py"

# INSTALL THE MONITOR SCRIPT (this is new)
say "Installing background monitor…"
curl -fsSL "$REPO/monitor.sh" -o "$DIR/monitor.sh"
chmod +x "$DIR/monitor.sh"

mkdir -p "$HOME/Library/Application Support/$LABEL"
cat > "$HOME/Library/Application Support/$LABEL/monitor.conf" <<'SETTINGS'
# Monitor configuration (generated by installer)
timeout=60
alert_enabled=true
log_level=INFO
SETTINGS

mkdir -p "$HOME/Library/Logs/jgonzalez007"

# Create launchd job for daemon mode
cat > "$HOME/Library/LaunchAgents/$LABEL.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>$LABEL</string>
  
  <key>ProgramArguments</key>
  <array>
    <string>/usr/bin/sudo</string>
    <string>/Users/$(whoami)/.netdiag/app/monitor.sh</string>
    <string>--daemon</string>
  </array>
  
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>/usr/local/bin:/opt/homebrew/bin:/Users/$(whoami)/.local/bin:$(pwd):~/bin:~/usr/bin:/usr/local/bin:/usr/bin:/bin</string>
  </dict>
  
  <key>RunAtLoad</key><true/>
  <key>StartInterval</key><integer>60</integer>
  
  <key>StandardOutPath</key><string>/Users/$(whoami)/Library/Logs/jgonzalez007/network-doctor.log</string>
  <key>StandardErrorPath</key><string>/Users/$(whoami)/Library/Logs/jgonzalez007/network-doctor.log</string>
  
  <key>KeepAlive</key><false/>
  <key>LimitLoadToSZ</key><true/>
</dict></plist>
PLIST

chmod 644 "$HOME/Library/LaunchAgents/$LABEL.plist"

# Load the launchd job (starts the daemon)
launchctl load "$HOME/Library/LaunchAgents/$LABEL.plist" >/dev/null

# Create the app bundle
mkdir -p "$APP/Contents/MacOS"
cat > "$APP/Contents/Info.plist" <<'PLIST2'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>Network Doctor</string>
  <key>CFBundleIdentifier</key><string>$LABEL</string>
  <key>CFBundleExecutable</key><string>network-doctor</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict></plist>
PLIST2

cat > "$APP/Contents/MacOS/network-doctor" <<'LAUNCHER'
#!/bin/bash
# Opens the dashboard when clicked from Launchpad or Spotlight
open http://127.0.0.1:8765
exit 0
LAUNCHER
chmod +x "$APP/Contents/MacOS/network-doctor"

# Stop any old daemon so the new code runs
launchctl bootout "gui/$(id -u)/$LABEL" >/dev/null 2>&1 || true

say "Done. Opening Network Doctor…"
open "$APP"

echo ""
echo "Next time, open it from Spotlight or Launchpad: \"Network Doctor\""
echo ""
echo "To stop the background monitor (optional):"
echo "  sudo launchctl bootout gui/\$(id -u)/com.jgonzalez007.network-doctor"
echo ""
echo "Logs: ~/Library/Logs/jgonzalez007/network-doctor.log"
